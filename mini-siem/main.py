#!/usr/bin/env python3
"""Mini SIEM command line.

  python main.py demo                         generate sample logs + ingest + detect
  python main.py ingest FILE --type ssh|web   parse a log file into the database
  python main.py detect                       run detection rules, print alerts
  python main.py report                       write reports/alerts.csv + reports/blocklist.sh
"""
import argparse
import csv
import os
import sys

from siem import detector, storage
from siem import parser as logparser
from siem.config import ROOT, load_config

COLORS = {"critical": "\033[1;31m", "high": "\033[31m", "medium": "\033[33m", "low": "\033[32m"}
RESET = "\033[0m"


def print_alerts(alerts):
    if not alerts:
        print("No alerts. Nothing suspicious found.")
        return
    print(f"\n{'SEVERITY':<9} {'RULE':<19} {'IP':<16} {'COUNT':>5}  {'FIRST SEEN':<19}  DETAILS")
    print("-" * 110)
    for a in alerts:
        c = COLORS.get(a["severity"], "") if sys.stdout.isatty() else ""
        r = RESET if c else ""
        print(f"{c}{a['severity'].upper():<9}{r} {a['rule']:<19} {a['ip']:<16} {a['count']:>5}  "
              f"{a['first_seen']:%Y-%m-%d %H:%M:%S}  {a['details']}")
    print(f"\nTotal alerts: {len(alerts)}")


def do_ingest(cfg, path, kind, reset):
    conn = storage.connect(cfg["db_path"])
    if reset:
        storage.reset_events(conn)
    events = logparser.parse_file(path, kind, cfg["log_year"], cfg["login_paths"])
    n = storage.insert_events(conn, events)
    print(f"[ingest] {path}: {n} login events stored ({kind})")
    return conn


def do_detect(cfg):
    conn = storage.connect(cfg["db_path"])
    events = storage.load_events(conn)
    alerts = detector.run_all(events, cfg["detection"])
    storage.save_alerts(conn, alerts)
    print(f"[detect] analysed {len(events)} events")
    print_alerts(alerts)
    return alerts


def do_report(cfg):
    conn = storage.connect(cfg["db_path"])
    alerts = detector.run_all(storage.load_events(conn), cfg["detection"])
    out = os.path.join(ROOT, "reports")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "alerts.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["severity", "rule", "ip", "username", "first_seen", "last_seen", "count", "details"])
        for a in alerts:
            w.writerow([a["severity"], a["rule"], a["ip"], a["username"], a["first_seen"],
                        a["last_seen"], a["count"], a["details"]])
    bad = sorted({a["ip"] for a in alerts if a["ip"] != "multiple"
                  and a["rule"] in ("brute_force", "password_spraying", "success_after_fail")})
    with open(os.path.join(out, "blocklist.sh"), "w", encoding="utf-8") as f:
        f.write("#!/bin/sh\n# REVIEW BEFORE RUNNING. Generated by Mini SIEM.\n")
        for ip in bad:
            f.write(f"iptables -A INPUT -s {ip} -j DROP\n")
    print(f"[report] {len(alerts)} alerts -> reports/alerts.csv ; {len(bad)} IPs -> reports/blocklist.sh")


def main():
    p = argparse.ArgumentParser(description="Mini SIEM - log analysis & brute-force detection")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("demo", help="generate sample logs, ingest and detect")
    i = sub.add_parser("ingest", help="parse a log file into the DB")
    i.add_argument("file")
    i.add_argument("--type", choices=["ssh", "web"], required=True)
    i.add_argument("--reset", action="store_true", help="wipe old events first")
    sub.add_parser("detect", help="run detection rules")
    sub.add_parser("report", help="export alerts.csv and blocklist.sh")
    args = p.parse_args()
    cfg = load_config()

    if args.cmd == "demo":
        from generate_logs import generate
        ssh_path, web_path = generate(os.path.join(ROOT, "data"))
        do_ingest(cfg, ssh_path, "ssh", reset=True)
        do_ingest(cfg, web_path, "web", reset=False)
        do_detect(cfg)
        do_report(cfg)
        print("\nDone. Start the dashboard with:  streamlit run dashboard.py")
    elif args.cmd == "ingest":
        if not os.path.exists(args.file):
            sys.exit(f"File not found: {args.file}")
        do_ingest(cfg, args.file, args.type, args.reset)
    elif args.cmd == "detect":
        do_detect(cfg)
    elif args.cmd == "report":
        do_report(cfg)


if __name__ == "__main__":
    main()
